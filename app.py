def evaluate_model(name, y_true, y_pred, train_time=None, inference_time=None, n_params=None):
    """Evaluasi standar yang disesuaikan untuk multi-kelas (3 kategori)."""
    acc = accuracy_score(y_true, y_pred)
    # Menggunakan average='weighted' karena label memiliki jumlah data yang tidak seimbang (imbalanced)
    prec = precision_score(y_true, y_pred, average='weighted', zero_division=0)
    rec = recall_score(y_true, y_pred, average='weighted', zero_division=0)
    f1 = f1_score(y_true, y_pred, average='weighted', zero_division=0)

    results_summary[name] = {
        "accuracy": acc, "precision": prec, "recall": rec, "f1": f1,
        "train_time": train_time, "inference_time": inference_time, "n_params": n_params
    }

    print(f"=== {name} ===")
    print(f"Accuracy : {acc:.4f}")
    print(f"Precision: {prec:.4f} (Weighted)")
    print(f"Recall   : {rec:.4f} (Weighted)")
    print(f"F1-Score : {f1:.4f} (Weighted)")
    if train_time: print(f"Waktu training : {train_time:.2f}s")
    if inference_time: print(f"Waktu inference: {inference_time*1000:.2f}ms")
    print()
    return results_summary[name]

