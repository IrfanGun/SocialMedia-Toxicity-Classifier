def build_rnn_model(
    rnn_type="LSTM", units=64, bidirectional=False, vocab_size=5000, embed_dim=64
):
  """Builder fleksibel untuk LSTM, GRU, atau BiLSTM (3 Kelas)."""
  inputs = keras.Input(shape=(MAX_LEN,))
  x = layers.Embedding(vocab_size, embed_dim)(inputs)

  if rnn_type == "LSTM":
    rnn_layer = layers.LSTM(units)
  elif rnn_type == "GRU":
    rnn_layer = layers.GRU(units)

  if bidirectional:
    x = layers.Bidirectional(rnn_layer)(x)
  else:
    x = rnn_layer(x)

  x = layers.Dense(32, activation="relu")(x)
  x = layers.Dropout(0.3)(x)

  # PERBAIKAN: Menambahkan (x) agar menjadi KerasTensor
  outputs = layers.Dense(3, activation="softmax")(x)

  name = f"{'Bi' if bidirectional else ''}{rnn_type}"
  return keras.Model(inputs, outputs, name=name)


def train_and_eval_rnn(model_name, rnn_type, bidirectional=False, epochs=20):
    model = build_rnn_model(
        rnn_type=rnn_type, units=64, bidirectional=bidirectional
    )
    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=1e-3),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"],
    )

    cb = [
        keras.callbacks.EarlyStopping(
            monitor="val_loss", patience=3, restore_best_weights=True
        )
    ]

    t0 = time.time()
    # Tambahkan class_weight=class_weight_dict di sini
    history = model.fit(
        X_train_seq,
        y_train,
        validation_data=(X_val_seq, y_val),
        epochs=epochs,
        batch_size=32,
        class_weight=class_weight_dict,
        callbacks=cb,
        verbose=1,
    )
    train_time = time.time() - t0

    t0 = time.time()
    y_pred_proba = model.predict(X_test_seq, verbose=0)
    inference_time = (time.time() - t0) / len(X_test_raw)
    y_pred = np.argmax(y_pred_proba, axis=1)

    evaluate_model(
        model_name,
        y_test,
        y_pred,
        train_time,
        inference_time,
        model.count_params(),
    )
    return model, history


